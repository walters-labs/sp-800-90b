#[test]
#[ignore = "requires NIST_REFERENCE_DIR and NIST_RESTART_REFERENCE; sanity-pass entropy-rejection parity"]
fn positive_entropy_rejection_after_sanity_pass_matches_reference() {
    // A checkerboard has perfectly balanced rows AND columns, but both
    // flattened orderings are highly predictable. This isolates the entropy
    // threshold failure from the sanity test's symbol-frequency failure.
    let data: Vec<u8> = (0..RESTART_SAMPLES)
        .map(|i| ((i / 1000 + i % 1000) % 2) as u8)
        .collect();
    compare_positive_restart(
        "entropy-rejected",
        &data,
        1,
        "0.5",
        RestartDecision::EntropyRejected,
        RestartMode::NonIid,
    );
}

