use rug::Float;
use sp_800_90b::*;
use std::{fs, path::PathBuf, process::Command};
#[test]
#[ignore = "requires NIST_REFERENCE_DIR; full million-sample non-IID restart assessment"]
fn full_non_iid_restart_matches_reference() {
    let root = PathBuf::from(std::env::var_os("NIST_REFERENCE_DIR").unwrap());
    let path = root.join("bin/truerand_1bit.bin");
    let data = fs::read(&path).unwrap();
    let out = Command::new(root.join("cpp/ea_restart"))
        .env("OMP_NUM_THREADS", "1")
        .args(["-n", "-v"])
        .arg(path)
        .args(["1", "0"])
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let text = String::from_utf8(out.stdout).unwrap();
    let r = assess_restart(
        &data,
        &Float::with_val(256, 0),
        RestartOptions {
            simulation_seed: Some([1, 2, 3, 4]),
            ..Default::default()
        },
    )
    .unwrap();
    assert_eq!(r.decision, RestartDecision::Validated);
    assert_eq!(r.min_entropy.unwrap(), 0);
    for (label, dataset) in [("H_r: ", r.rows.unwrap()), ("H_c: ", r.columns.unwrap())] {
        let value: f64 = text
            .lines()
            .find_map(|line| line.strip_prefix(label))
            .unwrap()
            .parse()
            .unwrap();
        assert!(
            (dataset.min_entropy().to_f64() - value).abs() < 1e-6,
            "{label}"
        );
        assert!(dataset.is_complete());
    }
}

#[test]
#[ignore = "requires NIST_REFERENCE_DIR; full million-sample IID checks"]
fn iid_restart_retains_incomplete_checks_and_literal_entropy() {
    let root = PathBuf::from(std::env::var_os("NIST_REFERENCE_DIR").unwrap());
    let data = fs::read(root.join("bin/truerand_4bit.bin")).unwrap();
    let r = assess_restart(
        &data,
        &Float::with_val(256, 0),
        RestartOptions {
            mode: RestartMode::Iid,
            simulation_seed: Some([1, 2, 3, 4]),
            permutation: PermutationOptions {
                seed: Some([0; 4]),
                ..Default::default()
            },
            ..Default::default()
        },
    )
    .unwrap();
    assert_eq!(r.decision, RestartDecision::Incomplete);
    assert!(r.min_entropy.is_none());
    let expected = most_common_value(&data).unwrap().min_entropy;
    for dataset in [r.rows.unwrap(), r.columns.unwrap()] {
        assert_eq!(dataset.min_entropy(), &expected);
        let RestartDatasetAssessment::Iid { checks, .. } = dataset else {
            panic!("wrong mode")
        };
        assert!(matches!(
            checks.permutation,
            Err(PermutationError::ZeroSeed)
        ));
        assert!(
            checks.independence.is_ok()
                && checks.goodness_of_fit.is_ok()
                && checks.longest_repeated_substring.is_ok()
        );
    }
}

#[test]
#[ignore = "requires NIST_RESTART_REFERENCE; five-million-round simulation parity"]
fn positive_entropy_sanity_cutoff_matches_reference() {
    let binary = std::env::var_os("NIST_RESTART_REFERENCE").unwrap();
    let output = Command::new(binary)
        .args(["1", &RESTART_SIMULATIONS.to_string()])
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let expected: usize = String::from_utf8(output.stdout)
        .unwrap()
        .trim()
        .parse()
        .unwrap();
    let data = [0, 1].repeat(RESTART_SAMPLES / 2);
    let result = restart_sanity_check(
        &data,
        &Float::with_val(256, 1),
        RestartOptions {
            simulation_seed: Some([1, 2, 3, 4]),
            ..Default::default()
        },
    )
    .unwrap();
    assert_eq!(result.cutoff, expected);
    assert!(result.reject);
    assert_eq!(result.maximum_row_count, 500);
    assert_eq!(result.maximum_column_count, 1000);
}

/// A private, unique input file lets both implementations consume identical
/// generated bytes. Drop removes only the file created by this test.
struct RestartInput(PathBuf);
impl RestartInput {
    fn new(name: &str, samples: &[u8]) -> Self {
        use std::io::Write;
        let path =
            std::env::temp_dir().join(format!("nist-restart-{name}-{}.bin", std::process::id()));
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
            .unwrap();
        file.write_all(samples).unwrap();
        Self(path)
    }
}
impl Drop for RestartInput {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.0);
    }
}
fn reference_number(text: &str, label: &str) -> f64 {
    text.lines()
        .find_map(|line| line.strip_prefix(label))
        .unwrap_or_else(|| panic!("missing {label} in reference output:\n{text}"))
        .trim()
        .parse()
        .unwrap()
}

fn compare_positive_restart(
    name: &str,
    data: &[u8],
    width: u8,
    h: &str,
    expected: RestartDecision,
    mode: RestartMode,
) {
    assert_eq!(data.len(), RESTART_SAMPLES);
    let root = PathBuf::from(std::env::var_os("NIST_REFERENCE_DIR").unwrap());
    let input = RestartInput::new(name, data);
    eprintln!("{name}: NIST CLI assessment (width={width}, H_I={h}, five million sanity rounds)");
    let mut command = if mode == RestartMode::Iid {
        let mut command = Command::new(std::env::var_os("NIST_RESTART_REFERENCE").unwrap());
        command.arg("--cli");
        command
    } else {
        Command::new(root.join("cpp/ea_restart"))
    };
    let output = command
        .env("OMP_NUM_THREADS", "1")
        .args([
            if mode == RestartMode::Iid { "-i" } else { "-n" },
            "-vv",
            "-s",
            &RESTART_SIMULATIONS.to_string(),
        ])
        .arg(&input.0)
        .args([&width.to_string(), h])
        .output()
        .unwrap();
    let text = String::from_utf8(output.stdout).unwrap();
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        text.contains("Restart Sanity Check Passed"),
        "{name}: {text}\n{stderr}"
    );
    let native_max = reference_number(&text, "X_max: ") as usize;
    let native_cutoff: usize = text
        .lines()
        .find_map(|line| line.split_once("X_cutoff: "))
        .unwrap()
        .1
        .trim()
        .parse()
        .unwrap();
    assert!(native_max <= native_cutoff);
    if expected == RestartDecision::Validated {
        assert!(output.status.success(), "{name}: {text}\n{stderr}");
        assert!(text.contains("Validation Test Passed"));
    } else {
        assert_eq!(expected, RestartDecision::EntropyRejected);
        assert_eq!(output.status.code(), Some(255), "{name}: {text}\n{stderr}");
        assert!(text.contains("min(H_r, H_c) < H_I/2, Validation Testing Failed"));
        assert!(!text.contains("Validation Test Passed"));
        assert!(!text.contains("min(H_r, H_c, H_I):"));
    }

    if mode == RestartMode::Iid {
        for label in [
            "Chi square tests: Passed",
            "Length of longest repeated substring test: Passed",
            "IID permutation tests: Passed",
        ] {
            assert!(text.contains(label), "{name}: missing {label}: {text}");
        }
        assert!(
            !text.contains("tests: Failed") && !text.contains("test: Failed"),
            "{name}: {text}"
        );
    }

    // The native CLI seeds from the OS. Exact cutoff parity uses the independent
    // simulator adapter with the same fixed seed as Rust instead.
    let seeded_cutoff = if mode == RestartMode::Iid {
        native_cutoff
    } else {
        eprintln!("{name}: fixed-seed NIST cutoff");
        let adapter = std::env::var_os("NIST_RESTART_REFERENCE").unwrap();
        let cutoff = Command::new(adapter)
            .args([h, &RESTART_SIMULATIONS.to_string()])
            .output()
            .unwrap();
        assert!(
            cutoff.status.success(),
            "{}",
            String::from_utf8_lossy(&cutoff.stderr)
        );
        let seeded_cutoff: usize = String::from_utf8(cutoff.stdout)
            .unwrap()
            .trim()
            .parse()
            .unwrap();
        seeded_cutoff
    };
    eprintln!("{name}: Rust assessment");
    let initial = Float::with_val(256, Float::parse(h).unwrap());
    let result = assess_restart(
        data,
        &initial,
        RestartOptions {
            mode,
            permutation: PermutationOptions {
                seed: Some([1, 2, 3, 4]),
                ..Default::default()
            },
            bits_per_symbol: Some(width),
            simulation_seed: Some([1, 2, 3, 4]),
            ..Default::default()
        },
    )
    .unwrap();
    assert_eq!(result.decision, expected, "{name}");
    assert!(!result.sanity.reject);
    assert_eq!(result.sanity.cutoff, seeded_cutoff, "{name}: seeded cutoff");
    assert_eq!(
        result
            .sanity
            .maximum_row_count
            .max(result.sanity.maximum_column_count),
        native_max
    );
    for (label, row) in [
        ("H_r: ", result.rows.as_ref().unwrap()),
        ("H_c: ", result.columns.as_ref().unwrap()),
    ] {
        assert!(row.is_complete(), "{name}: incomplete {label}");
        if mode == RestartMode::Iid {
            let RestartDatasetAssessment::Iid { checks, .. } = row else {
                panic!("{name}: wrong assessment mode");
            };
            assert!(!checks.independence.as_ref().unwrap().reject_independence);
            assert!(
                !checks
                    .goodness_of_fit
                    .as_ref()
                    .unwrap()
                    .reject_goodness_of_fit
            );
            assert!(!checks.longest_repeated_substring.as_ref().unwrap().reject);
            assert!(!checks.permutation.as_ref().unwrap().reject);
        }
        let actual = row.min_entropy().to_f64();
        let reference = reference_number(&text, label);
        eprintln!("{name}: {label}Rust={actual:.17}, NIST={reference:.6}");
        // The CLI prints these summaries to six decimal places.
        assert!(
            (actual - reference).abs() < 1e-6,
            "{name}: {label}{actual} vs {reference}"
        );
    }
    let row = result.rows.as_ref().unwrap().min_entropy();
    let col = result.columns.as_ref().unwrap().min_entropy();
    let minimum = row.clone().min(col);
    let threshold = Float::with_val(256, &initial / 2);
    if expected == RestartDecision::Validated {
        assert!(minimum >= threshold);
        let awarded = result.min_entropy.as_ref().unwrap();
        assert!(awarded > &0);
        assert_eq!(awarded, &initial.min(&minimum));
        assert!((awarded.to_f64() - reference_number(&text, "min(H_r, H_c, H_I): ")).abs() < 1e-6);
    } else {
        assert!(minimum < threshold);
        assert!(result.min_entropy.is_none());
    }
    eprintln!(
        "{name}: matched {expected:?}; max={native_max}, CLI cutoff={native_cutoff}, seeded cutoff={seeded_cutoff}"
    );
}

#[test]
#[ignore = "requires NIST_REFERENCE_DIR and NIST_RESTART_REFERENCE; full positive-entropy restart parity"]
fn positive_binary_restart_matches_reference() {
    let root = PathBuf::from(std::env::var_os("NIST_REFERENCE_DIR").unwrap());
    let data = fs::read(root.join("bin/truerand_1bit.bin")).unwrap();
    compare_positive_restart(
        "positive-binary",
        &data,
        1,
        "0.5",
        RestartDecision::Validated,
        RestartMode::NonIid,
    );
}

